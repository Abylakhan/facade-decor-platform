/** Classic cornice: fillet, cove (cavetto), ovolo, corona. Wall at x = 0. */
export function corniceProfile(h: number, p: number): ProfilePoint[] {
  const pts: ProfilePoint[] = [[0, 0], [p * 0.12, 0], [p * 0.12, h * 0.07], [p * 0.16, h * 0.07]];
  for (let i = 1; i <= 8; i++) {
    const t = i / 8;
    pts.push([p * (0.16 + 0.5 * (1 - Math.cos((t * Math.PI) / 2))), h * (0.07 + 0.45 * Math.sin((t * Math.PI) / 2))]);
  }
  pts.push([p * 0.72, h * 0.58], [p * 0.76, h * 0.58]);
  for (let i = 1; i <= 6; i++) {
    const t = i / 6;
    pts.push([p * (0.76 + 0.2 * Math.sin((t * Math.PI) / 2)), h * (0.58 + 0.16 * (1 - Math.cos((t * Math.PI) / 2)))]);
  }
  pts.push([p, h * 0.78], [p, h], [0, h]);
  return pts.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
}

/** Flat band with a rounded nosing and a small bead — moldings, belts, surrounds. */
export function bandProfile(h: number, p: number): ProfilePoint[] {
  const pts: ProfilePoint[] = [[0, 0], [p * 0.7, 0], [p * 0.7, h * 0.12], [p * 0.85, h * 0.18]];
  for (let i = 1; i <= 5; i++) {
    const t = i / 5;
    pts.push([p * (0.85 + 0.15 * Math.sin(t * Math.PI)), h * (0.18 + 0.14 * t)]);
  }
  pts.push([p * 0.75, h * 0.34], [p * 0.75, h * 0.86], [p, h * 0.9], [p, h], [0, h]);
  return pts.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
}

/** Sloped plinth profile (water drip on top). */
export function plinthProfile(h: number, p: number): ProfilePoint[] {
  return [[0, 0], [p, 0], [p, h * 0.7], [p * 0.85, h * 0.78], [p * 0.25, h], [0, h]];
}

